/**
 * Shared API envelope and error vocabulary (BACKEND_PRD section 11).
 * Protocol endpoints (OAuth, MCP JSON-RPC) keep their own native shapes.
 */

export interface ResponseMeta {
  request_id: string;
  [key: string]: unknown;
}

export interface SuccessEnvelope<T> {
  data: T;
  meta: ResponseMeta;
}

export interface ErrorBody {
  code: string;
  message: string;
  retryable: boolean;
  details?: Record<string, unknown>;
}

export interface ErrorEnvelope {
  error: ErrorBody;
  meta: ResponseMeta;
}

export interface CursorPage<T> {
  items: T[];
  has_more: boolean;
  next_cursor: string | null;
}

export const PAGE_DEFAULT_LIMIT = 20;
export const PAGE_MAX_LIMIT = 100;

